export function toJson(wf) {
  return { name: wf.name, nodes: wf.nodes, connections: wf.connections, settings: wf.settings };
}

export function checkWiring(wf) {
  const names = new Set(wf.nodes.map((n) => n.name));
  if (names.size !== wf.nodes.length) throw new Error(wf.name + ': duplicate node names');
  for (const [from, c] of Object.entries(wf.connections)) {
    if (!names.has(from)) throw new Error(wf.name + ': connection from unknown node ' + from);
    for (const out of c.main) for (const t of out) if (!names.has(t.node)) throw new Error(wf.name + ': ' + from + ' → unknown node ' + t.node);
  }
}

